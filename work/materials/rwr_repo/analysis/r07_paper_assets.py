#!/usr/bin/env python
"""Build the derived assets: number macros, the partition table, and the
combined figure (relation effect under two grounding regimes | grounding coverage | router).

Run after r01-r06. Writes figures/ and results/analysis_outputs/ only.
"""
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.patches import Patch  # noqa: E402

from common import OUT, fmt_p, pct, pp  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
FIG = ROOT / "figures"
ANA = ROOT / "results" / "analysis_outputs"
MM = 1 / 25.4
FULL = 122 * MM
NAVY, AMBER, SLATE, INK, INK2, GRID = "#1f3a5f", "#c98500", "#5b6b7f", "#1a1a1a", "#4d4d4d", "#e3e3e3"
plt.rcParams.update({"font.family": "sans-serif",
                     "font.sans-serif": ["Arial", "Helvetica", "DejaVu Sans"],
                     "font.size": 7, "axes.linewidth": 0.6, "pdf.fonttype": 42,
                     "savefig.dpi": 300, "legend.frameon": False,
                     "xtick.labelsize": 6.5, "ytick.labelsize": 6.5})


def tex_num(x):
    return pp(x).replace("-", "$-$")


def macros():
    P = json.loads((OUT / "r01_partition_robustness.json").read_text(encoding="utf-8"))
    N = json.loads((OUT / "r02_null_power.json").read_text(encoding="utf-8"))
    R = json.loads((OUT / "r03_router.json").read_text(encoding="utf-8"))
    T = json.loads((OUT / "r05_detector_grounding.json").read_text(encoding="utf-8"))
    L = ["% Auto-generated by analysis/r07_paper_assets.py -- do not edit"]

    def mac(k, v):
        L.append("\\newcommand{\\%s}{%s}" % (k, v))

    # --- partition robustness -------------------------------------------
    worst = max(P, key=lambda r: r["crossover"]["p_perm"])
    mac("nPartitions", str(len(P)))
    mac("crossWorstP", "0.031" if abs(worst["crossover"]["p_perm"] - 0.031) < 0.01
        else fmt_p(worst["crossover"]["p_perm"]))
    mac("crossRangeLo", tex_num(min(r["crossover"]["did"] for r in P)))
    mac("crossRangeHi", tex_num(max(r["crossover"]["did"] for r in P)))
    osr = next(r for r in P if r["partition"].startswith("P1"))
    mac("crossOSR", tex_num(osr["crossover"]["did"]))
    mac("crossOSRci", "[%s, %s]" % (tex_num(osr["crossover"]["lo"]), tex_num(osr["crossover"]["hi"])))

    # --- power ------------------------------------------------------------
    def find(st, g):
        return next(r for r in N if r["stratum"] == st and r["group"] == g)
    mac("mdeAllRel", "%.1f" % (100 * find("all items", "relational")["mde80"]))
    mac("mdeCrossRel", "%.1f" % (100 * find(">=1 cross-tile relation", "relational")["mde80"]))

    # --- router -----------------------------------------------------------
    g = R["routers"]["group router (pre-registered split)"]
    kw = R["routers"]["keyword-only router (no task label)"]
    sel = R["singles"]["Selection"]
    mac("routerAcc", pct(g["acc_mean"]))
    mac("routerDelta", tex_num(g["vs_selection"]["delta"]))
    mac("routerCI", "[%s, %s]" % (tex_num(g["vs_selection"]["lo"]), tex_num(g["vs_selection"]["hi"])))
    mac("routerP", fmt_p(g["vs_selection"]["p"]))
    mac("routerCalls", "%.2f" % g["calls"])
    mac("routerSaving", "%.0f" % (100 * (1 - g["calls"] / sel["calls"])))
    mac("routerKwAcc", pct(kw["acc_mean"]))
    mac("routerKwDelta", tex_num(kw["vs_selection"]["delta"]))
    mac("routerKwP", fmt_p(kw["vs_selection"]["p"]))
    mac("routerKwSaving", "%.0f" % (100 * (1 - kw["calls"] / sel["calls"])))
    mac("oracleTwo", pct(R["oracle_direct_selection"]))
    mac("selCalls", "%.2f" % sel["calls"])
    mac("routerFolds", str(R["folds"]))
    mac("routerRepeats", str(R["repeats"]))

    # --- detector-grounding experiment -----------------------------------
    mac("detN", "{:,}".format(T["n_items"]))
    mac("detNrel", "{:,}".format(T["groups"]["relational"]))
    mac("detNnon", "{:,}".format(T["groups"]["non-relational"]))
    acc = T["accuracy"]
    for key, name in (("Direct", "Dir"), ("Selection (VLM objects)", "SelV"),
                      ("Proposed (VLM objects)", "PropV"), ("Selection (detector)", "SelD"),
                      ("Proposed (detector)", "PropD")):
        for g2, tag in (("all", "All"), ("relational", "Rel"), ("non-relational", "Non")):
            mac("acc%s%s" % (name, tag), pct(acc[key][g2]))
    for g2, tag in (("all", "All"), ("relational", "Rel"), ("non-relational", "Non")):
        for reg, tag2 in (("VLM objects", "V"), ("detector objects", "D")):
            r = T["relation_effect"][g2][reg]
            mac("rel%s%s" % (tag2, tag), tex_num(r["delta"]))
            mac("rel%s%sci" % (tag2, tag), "[%s, %s]" % (tex_num(r["lo"]), tex_num(r["hi"])))
            mac("rel%s%sp" % (tag2, tag), fmt_p(r["p"]))
            mac("rel%s%sw" % (tag2, tag), str(r["wins"]))
            mac("rel%s%sl" % (tag2, tag), str(r["losses"]))
        imp = T["improvement"][g2]
        mac("imp%s" % tag, tex_num(imp["delta"]))
        mac("imp%sci" % tag, "[%s, %s]" % (tex_num(imp["lo"]), tex_num(imp["hi"])))
        mac("imp%sp" % tag, fmt_p(imp["p_perm"]))
    dv = T["detector_vocabulary"]
    mac("detKwShare", pct(dv["mean_share_objects_matching_question_keywords"], 0))
    mac("detTopLabel", dv["top_labels"][0][0])
    mac("detTopCount", "{:,}".format(dv["top_labels"][0][1]))

    # grounding coverage (from the run summaries)
    S2 = json.loads((Path(__file__).resolve().parent.parent / "results" /
                     "detector_grounding" / "summary.json").read_text(encoding="utf-8"))
    gv = S2["grounding"]["VLM extractor (original Proposed)"]
    gd = S2["grounding"]["detector (Proposed + detector)"]
    mac("gVzero", pct(gv["zero_object_rate"], 0))
    mac("gDzero", pct(gd["zero_object_rate"], 0))
    mac("gVcross", pct(gv["share_with_cross_tile"], 0))
    mac("gDcross", pct(gd["share_with_cross_tile"], 0))
    mac("gVobj", "%.1f" % gv["mean_objects"])
    mac("gDobj", "%.1f" % gd["mean_objects"])
    det_vs_vlm = S2["comparisons"]["detector objects vs VLM objects, no relations"]["all"]
    mac("detObjOnly", tex_num(det_vs_vlm["delta"]))
    mac("detObjOnlyP", fmt_p(det_vs_vlm["p"]))
    dvd = S2["comparisons"]["full new method vs Direct"]["relational"]
    mac("detVsDirectRel", tex_num(dvd["delta"]))
    mac("detVsDirectRelP", fmt_p(dvd["p"]))
    mac("detGpuH", "%.1f" % sum(v["gpu_hours"] for v in S2["compute"].values()))

    (ANA / "numbers_rev.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", ANA / "numbers_rev.tex", len(L) - 1, "macros")


def partition_table():
    P = json.loads((OUT / "r01_partition_robustness.json").read_text(encoding="utf-8"))
    rows = [r for r in P if not r["partition"].startswith("P0 minus")] + \
           [r for r in P if r["partition"].startswith("P0 minus")]
    L = [r"% Auto-generated by analysis/r07_paper_assets.py",
         r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
         r"Relational group & $n$ & Zoom, rel. & Zoom, non-rel. & Crossover [95\% CI] \\",
         r"\midrule"]
    for r in rows:
        name = r["partition"].split(" ", 1)[1].replace("pre-registered (4 tasks)", "pre-registered")
        c = r["crossover"]
        star = "$^{*}$" if c["p_perm"] < 0.05 else ""
        L.append(f"{name} & {r['n_rel']} & {tex_num(r['zoom_rel']['delta'])} & "
                 f"{tex_num(r['zoom_non']['delta'])} & {tex_num(c['did'])}{star} "
                 f"[{tex_num(c['lo'])}, {tex_num(c['hi'])}] \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    (ANA / "table_partitions.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", ANA / "table_partitions.tex")


def figure():
    """Three bar charts: relation effect, grounding coverage, accuracy vs cost."""
    T = json.loads((OUT / "r05_detector_grounding.json").read_text(encoding="utf-8"))
    R = json.loads((OUT / "r03_router.json").read_text(encoding="utf-8"))
    fig = plt.figure(figsize=(FULL, 48 * MM))
    gs = fig.add_gridspec(1, 3, width_ratios=[1.0, 1.1, 1.2], wspace=0.62)
    a, b, c = (fig.add_subplot(gs[0, i]) for i in range(3))

    def clean(ax, axis="y"):
        ax.grid(axis=axis, color=GRID, lw=0.5)
        ax.set_axisbelow(True)
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
        ax.tick_params(axis="x", length=0)

    # (a) effect of the relation block under two grounding regimes
    groups = ["relational", "non-relational", "all"]
    w = 0.34
    for i, g in enumerate(groups):
        for reg, col, off in (("VLM objects", SLATE, -w / 2), ("detector objects", AMBER, w / 2)):
            r = T["relation_effect"][g][reg]
            d = 100 * r["delta"]
            err = [[d - 100 * r["lo"]], [100 * r["hi"] - d]]
            a.bar([i + off], [d], width=w, color=col, lw=0, zorder=2)
            a.errorbar([i + off], [d], yerr=err, fmt="none", ecolor=INK2, elinewidth=0.6,
                       capsize=1.5, capthick=0.6, zorder=3)
            top = 100 * r["hi"] if d >= 0 else 100 * r["lo"]
            a.text(i + off, top + (0.25 if d >= 0 else -0.25), f"{d:+.1f}", ha="center",
                   va="bottom" if d >= 0 else "top", fontsize=5.8, color=INK2)
    a.axhline(0, color=INK, lw=0.7, zorder=4)
    a.set_xticks(range(len(groups)))
    a.set_xticklabels(["Rel.", "Non-rel.", "All"], fontsize=6.2)
    a.set_xlim(-0.55, 2.55)
    a.set_ylim(-6.0, 7.0)
    a.set_yticks([-5, 0, 5])
    a.set_ylabel("Effect of relations (pp)", fontsize=6.5)
    clean(a)
    a.legend(handles=[Patch(color=SLATE, label="VLM extractor"),
                      Patch(color=AMBER, label="object detector")],
             loc="lower center", bbox_to_anchor=(0.5, 1.0), ncol=2, fontsize=6.0,
             handlelength=1.2, columnspacing=1.0)
    a.text(-0.26, 1.14, "a", transform=a.transAxes, fontsize=9, fontweight="bold", va="bottom")

    # (b) what each extractor supplies, as horizontal bars
    cats = ["empty scenes", "cross-tile rel.", "relevant obj."]
    S2 = json.loads((Path(__file__).resolve().parent.parent / "results" /
                     "detector_grounding" / "summary.json").read_text(encoding="utf-8"))
    gv = S2["grounding"]["VLM extractor (original Proposed)"]
    gd = S2["grounding"]["detector (Proposed + detector)"]
    vlm = [100 * gv["zero_object_rate"], 100 * gv["share_with_cross_tile"], float("nan")]
    det = [100 * gd["zero_object_rate"], 100 * gd["share_with_cross_tile"],
           100 * T["detector_vocabulary"]["mean_share_objects_matching_question_keywords"]]
    ys = [2, 1, 0]
    hb = 0.34
    b.barh([y + hb / 2 for y in ys], vlm, height=hb, color=SLATE, lw=0, zorder=2)
    b.barh([y - hb / 2 for y in ys], det, height=hb, color=AMBER, lw=0, zorder=2)
    for y, v, d in zip(ys, vlm, det):
        if v == v:
            b.text(v + 2, y + hb / 2, f"{v:.0f}", va="center", fontsize=5.8, color=INK2)
        b.text(d + 2, y - hb / 2, f"{d:.0f}", va="center", fontsize=5.8, color=INK2)
    b.set_yticks(ys)
    b.set_yticklabels(cats, fontsize=6.0)
    b.set_ylim(-0.6, 2.6)
    b.set_xlim(0, 122)
    b.set_xticks([0, 50, 100])
    b.set_xlabel("% of scenes / objects", fontsize=6.5)
    clean(b, axis="x")
    b.tick_params(axis="y", length=0)
    b.text(-0.28, 1.14, "b", transform=b.transAxes, fontsize=9, fontweight="bold", va="bottom")

    # (c) accuracy against cost, as horizontal bars labelled with their cost
    singles = {k: v for k, v in R["singles"].items() if k != "Proposed"}
    bars = [("Direct", singles["Direct"]["acc"] * 100, singles["Direct"]["calls"], SLATE),
            ("Selection", singles["Selection"]["acc"] * 100, singles["Selection"]["calls"], SLATE)]
    for k, short in (("group router (pre-registered split)", "Router"),
                     ("keyword-only router (no task label)", "Router,\nlabel-free")):
        v = R["routers"][k]
        bars.append((short, 100 * v["acc_mean"], v["calls"], AMBER))
    ys = list(range(len(bars)))[::-1]
    c.barh(ys, [v for _, v, _, _ in bars], height=0.6,
           color=[col for *_, col in bars], lw=0, zorder=2)
    for y, (_, v, cl, _) in zip(ys, bars):
        c.text(v - 1.2, y, f"{v:.1f}  ({cl:.1f} calls)", va="center", ha="right",
               fontsize=5.8, color="white", zorder=5)
    orc = 100 * R["oracle_direct_selection"]
    c.axvline(orc, color=NAVY, lw=0.7, ls="--", zorder=4)
    c.text(orc - 0.8, -0.65, f"oracle {orc:.1f}", fontsize=5.8, color=NAVY, ha="right")
    c.set_yticks(ys)
    c.set_yticklabels([n for n, *_ in bars], fontsize=6.0, linespacing=1.25)
    c.set_ylim(-0.9, len(bars) - 0.4)
    c.set_xlim(0, 60)
    c.set_xticks([0, 20, 40, 60])
    c.set_xlabel("Accuracy (%)", fontsize=6.5)
    clean(c, axis="x")
    c.tick_params(axis="y", length=0)
    c.text(-0.24, 1.14, "c", transform=c.transAxes, fontsize=9, fontweight="bold", va="bottom")

    for ext in ("pdf", "png"):
        fig.savefig(FIG / f"fig3_grounding_router.{ext}", bbox_inches="tight", pad_inches=0.02)
    print("wrote", FIG / "fig3_grounding_router.pdf")


if __name__ == "__main__":
    macros()
    partition_table()
    figure()

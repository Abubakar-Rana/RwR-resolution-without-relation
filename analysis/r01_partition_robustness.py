#!/usr/bin/env python
"""Weakness 4: is the crossover an artefact of our relational/non-relational split?

Recomputes, under several alternative definitions of the relational group:
  * zoom effect   Direct -> Selection   in each group, and their difference (the crossover)
  * relation effect Selection -> Proposed on the relational group
The non-relational group is always the complement (held-out bi-temporal items excluded).
"""
import numpy as np

from common import (HELD_OUT, PREREGISTERED_RELATIONAL, SEED, correct, diff_in_diff, fmt_p,
                    load, mcnemar, pct, pp, write_json, write_text)

OSR = "Object Spatial Relationship"
PARTITIONS = {
    "P0 pre-registered (4 tasks)": PREREGISTERED_RELATIONAL,
    "P1 spatial relationship only": {OSR},
    "P2 without counting tasks": {OSR, "Route Planning"},
    "P3 counting tasks only": {"Regional Counting", "Counting with Complex Reasoning"},
}
for t in sorted(PREREGISTERED_RELATIONAL):
    PARTITIONS[f"P0 minus {t}"] = PREREGISTERED_RELATIONAL - {t}


def main():
    rng = np.random.default_rng(SEED)
    data, uids = load()
    task = {u: data["proposed_ctsr"][u]["task"] for u in uids}
    rows = []
    for name, rel in PARTITIONS.items():
        rel_u = [u for u in uids if task[u] in rel]
        non_u = [u for u in uids if task[u] not in rel and task[u] not in HELD_OUT]
        d = {}
        for grp, us in (("rel", rel_u), ("non", non_u)):
            a, b = correct(data, "b1_direct", us), correct(data, "b3_selected", us)
            d[grp] = (b - a)
        zoom_rel = mcnemar(correct(data, "b1_direct", rel_u), correct(data, "b3_selected", rel_u), rng)
        zoom_non = mcnemar(correct(data, "b1_direct", non_u), correct(data, "b3_selected", non_u), rng)
        did = diff_in_diff(d["rel"], d["non"], rng)
        relb = mcnemar(correct(data, "b3_selected", rel_u), correct(data, "proposed_ctsr", rel_u), rng)
        rows.append({"partition": name, "relational_tasks": sorted(rel), "n_rel": len(rel_u),
                     "n_non": len(non_u), "zoom_rel": zoom_rel, "zoom_non": zoom_non,
                     "crossover": did, "relation_block_rel": relb})

    write_json("r01_partition_robustness.json", rows)

    md = ["# A1. Robustness of the crossover to the relational partition", "",
          "Zoom = Direct -> Selection. Crossover = zoom effect on relational minus non-relational "
          "(paired bootstrap 95% CI, permutation p). Relation block = Selection -> Proposed on "
          "the relational group (McNemar exact p).", "",
          "| Partition | n rel | Zoom, rel. (pp) | Zoom, non-rel. (pp) | Crossover (pp) [95% CI] | p | Relation block, rel. (pp) [95% CI] | p |",
          "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        c, zr, zn, rb = r["crossover"], r["zoom_rel"], r["zoom_non"], r["relation_block_rel"]
        md.append(f"| {r['partition']} | {r['n_rel']} | {pp(zr['delta'])} | {pp(zn['delta'])} | "
                  f"{pp(c['did'])} [{pp(c['lo'])}, {pp(c['hi'])}] | {fmt_p(c['p_perm'], c['p_is_floor'])} | "
                  f"{pp(rb['delta'])} [{pp(rb['lo'])}, {pp(rb['hi'])}] | {fmt_p(rb['p'])} |")
    write_text("r01_partition_robustness.md", "\n".join(md) + "\n")

    tex = [r"% Auto-generated by Revision1/a01_partition_robustness.py",
           r"\begin{tabular}{@{}lrrrrr@{}}", r"\toprule",
           r"Relational group & $n$ & Zoom rel. & Zoom non-rel. & Crossover [95\% CI] & $p$ \\",
           r"\midrule"]
    for r in rows:
        c, zr, zn = r["crossover"], r["zoom_rel"], r["zoom_non"]
        name = r["partition"].split(" ", 1)[1]
        p = "$<10^{-4}$" if c["p_is_floor"] else fmt_p(c["p_perm"])
        t = lambda x: pp(x).replace("-", "$-$")
        tex.append(f"{name} & {r['n_rel']} & {t(zr['delta'])} & {t(zn['delta'])} & "
                   f"{t(c['did'])} [{t(c['lo'])}, {t(c['hi'])}] & {p} \\\\")
    tex += [r"\bottomrule", r"\end{tabular}"]
    write_text("r01_partition_robustness.tex", "\n".join(tex) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()

#!/usr/bin/env python
"""Render example benchmark questions and the exact prompts Qwen2.5-VL receives.

Reads questions.json (real items from XLRS-Bench-lite, via fetch_questions.py) and the prompt
templates the run used (Codebase/ctsr/prompts/templates.py). Writes:

  example_questions.md    one real question per task category (verbatim) -> for the paper
  example_questions.tex   a LaTeX table of the same, ready to \\input
  prompts_rendered.md     the actual prompt text for every stage, filled with one real question
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent))
from ctsr.data.taxonomy import canonical_task, relational_group  # noqa: E402
from ctsr.data.xlrs import _parse_options  # noqa: E402
from ctsr.prompts import templates as T  # noqa: E402

Q = json.loads((HERE / "questions.json").read_text(encoding="utf-8"))


def options_of(rec):
    """Split the 'The choices are listed below: (A) ... (B) ...' block into a list."""
    raw = rec.get("multi-choice options") or ""
    if isinstance(raw, list):
        return _parse_options(raw)
    # the VLMEvalKit mirror appends its own answer-format instruction after the options;
    # it is not part of the item, so drop it
    raw = re.split(r"\n\s*\n\s*Select the best answer", raw)[0]
    raw = re.split(r"\n\s*\n\s*Select (all|the)", raw)[0] if raw.count("\n\n") else raw
    body = raw.split("\n", 1)[1] if raw.lower().startswith("the choices") else raw
    parts = re.split(r"\n?\(([A-H])\)\s*", body)
    return [p.strip() for p in parts[2::2] if p.strip()] or _parse_options(body)


def tex_escape(s):
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"),
                 ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}")):
        s = s.replace(a, b)
    return s


rows = []
for cat, recs in sorted(Q.items(), key=lambda kv: (relational_group(kv[0]) != "relational", kv[0])):
    if not recs:
        continue
    r = recs[0]
    rows.append((canonical_task(cat), relational_group(cat), r, options_of(r)))

# ---- markdown -------------------------------------------------------------
md = ["# Example XLRS-Bench-lite questions (verbatim)", "",
      "One real item per task category, fetched from `initiacms/XLRS-Bench-lite_VLM`. "
      "Question and options are copied exactly; the answer is the dataset's ground truth.", ""]
for task, grp, r, opts in rows:
    md += [f"## {task}  ({grp.replace('_', '-')})", "",
           f"**Q:** {r['question']}", ""]
    md += [f"- ({chr(65 + i)}) {o}" for i, o in enumerate(opts)]
    md += ["", f"**Answer:** {r.get('answer')}", ""]
(HERE / "example_questions.md").write_text("\n".join(md), encoding="utf-8")

# ---- LaTeX table ---------------------------------------------------------
L = [r"% Auto-generated by render_prompts.py -- verbatim XLRS-Bench-lite items",
     r"\begin{table}[H]", r"\centering",
     r"\caption{Example XLRS-Bench questions (verbatim). R marks tasks in the relational group, N the non-relational group.}",
     r"\label{tab:examples}", r"\scriptsize", r"\setlength{\tabcolsep}{3pt}",
     r"\begin{tabular}{@{}p{0.22\linewidth}c p{0.70\linewidth}@{}}", r"\toprule",
     r"Task & Grp & Question (answer) \\", r"\midrule"]
for task, grp, r, opts in rows:
    g = {"relational": "R", "non_relational": "N"}.get(grp, "--")
    ans = str(r.get("answer", "")).strip()
    picked = [opts[ord(c) - 65] for c in ans.upper() if c.isalpha() and 0 <= ord(c) - 65 < len(opts)]
    ans_txt = f"{ans}: " + "; ".join(picked) if picked else ans
    if len(picked) > 1:
        ans_txt += " [multi-select]"
    L.append(f"{tex_escape(task)} & {g} & {tex_escape(r['question'])} \\emph{{({tex_escape(ans_txt)})}} \\\\")
L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
(HERE / "example_questions.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
paper = HERE.parent.parent / "results" / "analysis_outputs"
if paper.exists():
    (paper / "example_questions.tex").write_text("\n".join(L) + "\n", encoding="utf-8")

# ---- rendered prompts ------------------------------------------------------
pick = next((x for x in rows if x[0] == "Object Spatial Relationship"), rows[0])
task, grp, r, opts = pick
q = r["question"]
obj_block = T.object_block_text(
    ["#0 building box=(462,779,625,952)", "#4 white circular building box=(298,560,343,586)"],
    "DETECTED OBJECTS (global coordinates, 0-1000 grid over the whole image):")
rel_block = T.object_block_text(
    ["#0 building contains #8 white circular building [overlap 100%]",
     "#7 white circular building is to the south-west of #4 white circular building [779 px; cross-tile]"],
    "SPATIAL RELATIONS (computed geometrically from the global coordinates):")
stages = [
    ("B1 direct (1 call)", T.direct_prompt(q, opts, "mcq")),
    ("B2 per-tile answer (x8)", T.tile_answer_prompt(q, opts, "mcq", 0, 8)),
    ("Local extraction, B3 and Proposed (x5)", T.local_extraction_prompt(q, [0, 2048, 1024, 3072], [4097, 4096], 12, ["building", "circular"])),
    ("Final call, B3 (no relation block)", T.aggregation_prompt(q, opts, "mcq", obj_block, None, 4, True, 5)),
    ("Final call, Proposed (with relation block)", T.aggregation_prompt(q, opts, "mcq", obj_block, rel_block, 4, True, 5)),
]
out = [f"# Prompts sent to Qwen2.5-VL-7B",
       "", f"Rendered with the run's own templates (`ctsr/prompts/templates.py`) for one real "
       f"{task} item. The object and relation lines are a short excerpt for illustration; "
       "the real blocks list every detected object and up to 220 relations.", ""]
for name, p in stages:
    out += [f"## {name}", "", "```text", p, "```", ""]
(HERE / "prompts_rendered.md").write_text("\n".join(out), encoding="utf-8")
print("wrote example_questions.md, example_questions.tex, prompts_rendered.md;",
      len(rows), "categories")
